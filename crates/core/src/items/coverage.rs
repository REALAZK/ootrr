use crate::items::model::{Counts, Item, Mode, Table, MODES};

const MODEL: &str = "\
## How the remake models each kind of item

- `actor`: one remake actor is the item. The `actor` field is the name to write into a chest `Dynamic.Drop__DropActor`.
- `tiers`: a progressive chain. The remake has one actor per tier and no counter flag. Copy number n of the OoTR item must be written as `tiers[n]`. Handing out the tiers in copy order never gives the player less than the logic assumes, provided each higher tier includes the lower ones. That is a GUESS from the pouch data and is not tested in game.
- `bundle`: a consumable with a fixed amount. `qty` is the amount the actor delivers (read from `PouchActorInfo` `BundleActorNum`). `approx` means the same family but a different amount.
- `bottle`: the empty bottle is `Item_Bottle` and every content is its own actor, so each content item should hand over a new bottle already filled. That is a GUESS and is not tested in game.
- `generic`: Map, Compass, Small Key and Boss Key are one generic actor each. The dungeon is not in the actor. It comes from the dungeon of the location that holds it (`DungeonParam` has one row per dungeon with its own game data target). Use `Table::generic(actor, dungeon)` to turn a pickup back into the OoTR item. An item can only leave its dungeon if the game keys the pouch by the current dungeon, which is not verified, so dungeon items stay in their own dungeon.
- `shop`: a shop slot actor (`Shop_*`). It can only appear in a shop slot, the price comes from the item.
- `logic`: an abstract OoTR token (events, drop sources, refills, empty slots) with no game item by design.
- `none`: a real OoTR item that the remake cannot grant. The reason is in the table.

Where an item can be granted (`via`): `chest` is a chest `Drop__DropActor`, `flow` is an event flow that gives or sells it, `world` is a free pickup or a non chest drop, `shop` is a placed shop slot. `seen` means observed in the dump data, `partial` means only some tiers were observed in chests, `guess` means the actor exists but was never observed in that role.
";

fn cell(s: &str) -> String {
    s.replace('|', "/")
}

fn actors(it: &Item) -> String {
    if it.mode == Mode::Tiers {
        return it.tiers.iter().map(|t| format!("`{t}`")).collect::<Vec<String>>().join(" > ");
    }
    let mut out: Vec<String> = Vec::new();
    if let Some(a) = &it.actor {
        out.push(format!("`{a}`"));
    }
    for w in &it.world {
        out.push(format!("(`{w}`)"));
    }
    out.join(" ")
}

fn status(it: &Item) -> &'static str {
    match it.mode {
        Mode::Logic => "logic only",
        Mode::None => "unmapped",
        _ => "mapped",
    }
}

fn summary(c: &Counts) -> String {
    let mut out: String = String::new();
    out.push_str(&format!("- Items: {}. Mapped: {}. Logic only: {}. Unmapped: {}.\n", c.total, c.mapped, c.logic, c.unmapped));
    out.push_str(&format!(
        "- Progression items: {}. Mapped: {}. Logic only: {}. Unmapped: {}.\n",
        c.adv, c.adv_mapped, c.adv_logic, c.adv_unmapped
    ));
    let modes: Vec<String> = MODES.iter().map(|m| format!("{} {}", m.name(), c.by_mode.get(m.name()).copied().unwrap_or(0))).collect();
    out.push_str(&format!("- By mode: {}.\n", modes.join(", ")));
    let confs: Vec<String> = c.by_conf.iter().map(|(k, v)| format!("{k} {v}")).collect();
    out.push_str(&format!("- Mapped by confidence: {}.\n", confs.join(", ")));
    let chest: Vec<String> = c.chest.iter().map(|(k, v)| format!("{k} {v}")).collect();
    out.push_str(&format!("- Chest channel: {}.\n", chest.join(", ")));
    out
}

pub fn render(t: &Table, unclaimed: Option<&[String]>) -> String {
    let c: Counts = t.counts();
    let mut out: String = String::new();
    out.push_str("# Item mapping coverage\n\n");
    out.push_str("Generated by `ootrr items-check` from `data/items.json`, which follows the item names of the OoT Randomizer `ItemList.py` (MIT, github.com/OoTRandomizer/OoT-Randomizer). Identifiers only.\n\n");
    out.push_str("## Summary\n\n");
    out.push_str(&summary(&c));
    out.push('\n');
    out.push_str(MODEL);
    out.push_str("\n## Items\n\n");
    out.push_str("| Item | Kind | Prog | Status | Mode | Remake actors | Conf | Qty | Where | Dungeon | Note |\n");
    out.push_str("|---|---|---|---|---|---|---|---|---|---|---|\n");
    for it in &t.items {
        out.push_str(&format!(
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |\n",
            cell(&it.name),
            it.kind,
            if it.adv { "yes" } else { "no" },
            status(it),
            it.mode.name(),
            actors(it),
            it.conf,
            it.qty.map(|q| q.to_string()).unwrap_or_default(),
            it.via.text(),
            it.dungeon.clone().unwrap_or_default(),
            cell(&it.why)
        ));
    }
    if let Some(u) = unclaimed {
        out.push_str("\n## Remake item rows that no OoTR item maps to\n\n");
        out.push_str(&format!("{} rows of `PouchActorInfo` without a `Pouch_`, `Weapon_` or `Armor_` prefix.\n\n", u.len()));
        for a in u {
            out.push_str(&format!("- `{a}`\n"));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::items::load::parse;

    fn table() -> Table {
        parse(
            "{\"format\":1,\"items\":[\
            {\"name\":\"Hook\",\"kind\":\"Item\",\"adv\":true,\"actor\":\"A1\",\"conf\":\"exact\",\"mode\":\"tiers\",\"tiers\":[\"A1\",\"A2\"],\"via\":{\"chest\":\"partial\"}},\
            {\"name\":\"Mask\",\"kind\":\"Item\",\"actor\":\"M\",\"conf\":\"exact\",\"world\":[\"Shop_M\"],\"why\":\"a | b\"},\
            {\"name\":\"Rings\",\"kind\":\"Item\",\"adv\":true,\"mode\":\"none\",\"why\":\"no ring\",\"world\":[\"Tok\"]},\
            {\"name\":\"Event\",\"kind\":\"Event\",\"mode\":\"logic\",\"why\":\"token\"}\
            ]}",
        )
        .unwrap()
    }

    #[test]
    fn every_item_gets_a_row_with_its_status() {
        let s: String = render(&table(), None);
        assert!(s.contains("| Hook | Item | yes | mapped | tiers | `A1` > `A2` | exact |"));
        assert!(s.contains("| Mask | Item | no | mapped | actor | `M` (`Shop_M`) |"));
        assert!(s.contains("| Rings | Item | yes | unmapped | none | (`Tok`) |"));
        assert!(s.contains("| Event | Event | no | logic only | logic |"));
        assert!(s.contains("a / b"));
    }

    #[test]
    fn the_summary_counts_add_up() {
        let s: String = render(&table(), None);
        assert!(s.contains("Items: 4. Mapped: 2. Logic only: 1. Unmapped: 1."));
        assert!(s.contains("Progression items: 2. Mapped: 1. Logic only: 0. Unmapped: 1."));
        assert!(s.contains("Chest channel: partial 1."));
    }

    #[test]
    fn the_unclaimed_section_is_optional() {
        assert!(!render(&table(), None).contains("no OoTR item maps to"));
        let s: String = render(&table(), Some(&["Item_X".to_string()]));
        assert!(s.contains("no OoTR item maps to"));
        assert!(s.contains("- `Item_X`"));
    }

    #[test]
    fn the_prose_has_no_dashes_or_semicolons() {
        let s: String = render(&table(), None);
        assert!(!s.contains('\u{2014}'));
        assert!(!s.contains(';'));
    }
}
