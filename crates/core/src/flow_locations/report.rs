use std::collections::BTreeMap as BM;
use std::fmt::Write as W;

use crate::flow_locations::data::{Data, Loc, Loose};

pub fn by_category(d: &Data) -> BM<String, (usize, usize)> {
    let mut m: BM<String, (usize, usize)> = BM::new();
    for l in &d.locs {
        let e: &mut (usize, usize) = m.entry(l.cat.clone()).or_insert((0, 0));
        if l.supported {
            e.0 += 1;
        } else {
            e.1 += 1;
        }
    }
    m
}

pub fn by_reason(d: &Data) -> BM<String, usize> {
    let mut m: BM<String, usize> = BM::new();
    for l in d.locs.iter().filter(|l| !l.supported) {
        *m.entry(l.why.clone()).or_insert(0) += 1;
    }
    m
}

pub fn by_kind(d: &Data) -> BM<String, (usize, usize, usize)> {
    let mut m: BM<String, (usize, usize, usize)> = BM::new();
    for l in &d.locs {
        let e: &mut (usize, usize, usize) = m.entry(l.kind.clone()).or_insert((0, 0, 0));
        if l.supported {
            e.0 += 1;
        } else {
            e.1 += 1;
        }
    }
    for g in &d.gaps {
        m.entry(g.kind.clone()).or_insert((0, 0, 0)).2 += 1;
    }
    m
}

pub fn check_list(d: &Data) -> Vec<&Loc> {
    let mut seen: Vec<&str> = Vec::new();
    let mut out: Vec<&Loc> = Vec::new();
    for l in d.locs.iter().filter(|l| l.supported) {
        if !seen.contains(&l.cat.as_str()) {
            seen.push(&l.cat);
            out.push(l);
        }
    }
    out
}

pub fn coverage(d: &Data) -> String {
    let mut o: String = String::new();
    let sup: usize = d.locs.iter().filter(|l| l.supported).count();
    let tot: usize = d.locs.len() + d.gaps.len();
    let _ = writeln!(
        o,
        "OoTR locations in scope: {}. Matched to flow events: {} ({} supported, {} unsupported). Unmatched: {}.",
        tot,
        d.locs.len(),
        sup,
        d.locs.len() - sup,
        d.gaps.len()
    );
    let _ = writeln!(o, "Flow events with no OoTR location: {}. Replacement names the game hands out: {}.", d.loose.len(), d.accept.len());
    let _ = writeln!(o, "By OoTR type (supported, unsupported, unmatched):");
    for (k, v) in by_kind(d) {
        let _ = writeln!(o, "  {k}: {} supported, {} unsupported, {} unmatched", v.0, v.1, v.2);
    }
    let _ = writeln!(o, "By category (supported, unsupported):");
    for (k, v) in by_category(d) {
        let _ = writeln!(o, "  {k}: {} supported, {} unsupported", v.0, v.1);
    }
    let _ = writeln!(o, "Why locations are unsupported:");
    for (k, n) in by_reason(d) {
        let _ = writeln!(o, "  {n} x {k}");
    }
    let _ = writeln!(o, "Why locations are unmatched:");
    let mut why: BM<&str, usize> = BM::new();
    for g in &d.gaps {
        *why.entry(g.reason.as_str()).or_insert(0) += 1;
    }
    for (k, n) in why {
        let _ = writeln!(o, "  {n} x {k}");
    }
    o
}

fn sites(l: &Loc) -> String {
    let v: Vec<String> = l.edits.iter().map(|e| format!("{} {}", e.file.trim_end_matches(".bfevfl"), e.index)).collect();
    v.join(", ")
}

pub fn markdown(d: &Data) -> String {
    let mut o: String = String::new();
    let sup: usize = d.locs.iter().filter(|l| l.supported).count();
    let _ = writeln!(o, "# Flow location coverage");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "Generated by `ootrr flow-locations-report --md` from `data/flow_locations.json`. Every OoTR location of type Song, Boss, Cutscene, NPC and Event (Master Quest excluded) is either matched to event flow events or listed with the reason it is not. Flow edits are verified on disk only, nothing here is verified in game."
    );
    let _ = writeln!(o);
    let _ = writeln!(o, "## Summary");
    let _ = writeln!(o);
    let _ = writeln!(
        o,
        "- OoTR locations in scope: {}. Matched: {} ({} supported, {} unsupported). Unmatched: {}.",
        d.locs.len() + d.gaps.len(),
        d.locs.len(),
        sup,
        d.locs.len() - sup,
        d.gaps.len()
    );
    let _ = writeln!(o, "- Flow events that hand out an item and belong to no OoTR location: {}.", d.loose.len());
    let _ = writeln!(o, "- Replacement names the game's own flows hand out: {}.", d.accept.len());
    let _ = writeln!(o);
    let _ = writeln!(o, "| OoTR type | Supported | Unsupported | Unmatched |");
    let _ = writeln!(o, "|---|---|---|---|");
    for (k, v) in by_kind(d) {
        let _ = writeln!(o, "| {k} | {} | {} | {} |", v.0, v.1, v.2);
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "| Category | Supported | Unsupported |");
    let _ = writeln!(o, "|---|---|---|");
    for (k, v) in by_category(d) {
        let _ = writeln!(o, "| {k} | {} | {} |", v.0, v.1);
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "Confidence levels in the `conf` field:");
    let _ = writeln!(o);
    let _ = writeln!(o, "- `item`: the flow grants the actor that matches the OoTR vanilla item and the flow identifies the location.");
    let _ = writeln!(o, "- `scene`: the flow, NPC or entry name identifies the location, the item is common or only matches by class.");
    let _ = writeln!(o, "- `guess`: the flow is the best candidate but the item or the path does not match cleanly.");
    let _ = writeln!(o);
    let _ = writeln!(o, "## Matched locations");
    let _ = writeln!(o);
    let _ = writeln!(o, "| OoTR location | Category | Conf | Support | Vanilla | Flow events (file and index) |");
    let _ = writeln!(o, "|---|---|---|---|---|---|");
    for l in &d.locs {
        let t: &str = if l.supported { "supported" } else { "unsupported" };
        let _ = writeln!(o, "| {} | {} | {} | {} | {} | {} |", l.name, l.cat, l.conf, t, l.vanilla, sites(l));
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "## Unsupported locations");
    let _ = writeln!(o);
    let _ = writeln!(o, "The build refuses these because each needs more than one parameter edit.");
    let _ = writeln!(o);
    for l in d.locs.iter().filter(|l| !l.supported) {
        let _ = writeln!(o, "- {}: {}.", l.name, l.why);
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "## Unmatched OoTR locations");
    let _ = writeln!(o);
    let _ = writeln!(o, "| OoTR location | Type | Vanilla | Reason |");
    let _ = writeln!(o, "|---|---|---|---|");
    for g in &d.gaps {
        let _ = writeln!(o, "| {} | {} | {} | {} |", g.name, g.kind, g.vanilla, g.reason);
    }
    let _ = writeln!(o);
    let _ = writeln!(o, "## Flow events with no OoTR location");
    let _ = writeln!(o);
    let mut by: BM<&str, Vec<&Loose>> = BM::new();
    for x in &d.loose {
        by.entry(x.reason.as_str()).or_default().push(x);
    }
    for (r, v) in by {
        let _ = writeln!(o, "{} events, {}:", v.len(), r);
        let _ = writeln!(o);
        let l: Vec<String> = v.iter().map(|x| format!("{} {} {}", x.file.trim_end_matches(".bfevfl"), x.index, x.item)).collect();
        let _ = writeln!(o, "{}", l.join(", "));
        let _ = writeln!(o);
    }
    o
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn counts_add_up() {
        let d: Data = Data::load().unwrap();
        let c: BM<String, (usize, usize)> = by_category(&d);
        let n: usize = c.values().map(|v| v.0 + v.1).sum();
        assert_eq!(n, d.locs.len());
        let k: BM<String, (usize, usize, usize)> = by_kind(&d);
        let m: usize = k.values().map(|v| v.0 + v.1 + v.2).sum();
        assert_eq!(m, d.locs.len() + d.gaps.len());
        let r: usize = by_reason(&d).values().sum();
        assert_eq!(r, d.locs.iter().filter(|l| !l.supported).count());
    }

    #[test]
    fn one_test_per_supported_category() {
        let d: Data = Data::load().unwrap();
        let t: Vec<&Loc> = check_list(&d);
        let cats: usize = by_category(&d).values().filter(|v| v.0 > 0).count();
        assert_eq!(t.len(), cats);
        assert!(t.iter().all(|l| l.supported));
        assert!(coverage(&d).contains("Matched to flow events"));
    }

    #[test]
    fn markdown_lists_every_location_without_em_dashes() {
        let d: Data = Data::load().unwrap();
        let m: String = markdown(&d);
        assert!(m.contains("## Matched locations"));
        assert!(!m.contains('\u{2014}'));
        for l in &d.locs {
            assert!(m.contains(&l.name), "{}", l.name);
        }
        for g in &d.gaps {
            assert!(m.contains(&g.name), "{}", g.name);
        }
    }
}
